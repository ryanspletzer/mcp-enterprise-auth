#Requires -Version 7.0
#Requires -Modules Microsoft.Graph.Authentication, Microsoft.Graph.Applications

<#
.SYNOPSIS
    Creates Entra ID app registrations for MCP Enterprise Auth project.

.DESCRIPTION
    Idempotently creates 8 app registrations in Microsoft Entra ID:
    - 1 MCP Server Resource API (with exposed scopes and app roles)
    - 5 Public clients (VS Code, Claude Desktop, Claude Code, ChatGPT, Generic)
    - 1 Confidential client (with client secret)
    - 1 Service Principal (with client secret and app role assignment)

    The script generates a .env file with all configuration values needed
    to run the MCP server and client examples.

.PARAMETER TenantId
    The Entra ID tenant ID. If not provided, will use the signed-in user's tenant.

.PARAMETER OutputEnvFile
    Path to output .env file. Defaults to repository root (.env).

.PARAMETER Force
    Force recreation of client secrets even if apps already exist.

.PARAMETER AppNamePrefix
    Prefix for app registration names. Defaults to "MCP".

.EXAMPLE
    .\Setup-EntraIdAppRegistrations.ps1
    Creates all app registrations using interactive authentication.

.EXAMPLE
    .\Setup-EntraIdAppRegistrations.ps1 -TenantId "12345678-1234-1234-1234-123456789abc"
    Creates app registrations in the specified tenant.

.EXAMPLE
    .\Setup-EntraIdAppRegistrations.ps1 -Force
    Recreates client secrets for existing apps.

.NOTES
    Requires Global Administrator or Application Administrator role.
    Required Microsoft Graph modules:
    - Microsoft.Graph.Authentication
    - Microsoft.Graph.Applications

    Install with: Install-Module Microsoft.Graph -Scope CurrentUser
#>

[CmdletBinding()]
param(
    [Parameter()]
    [string]$TenantId,

    [Parameter()]
    [string]$OutputEnvFile,

    [Parameter()]
    [switch]$Force,

    [Parameter()]
    [string]$AppNamePrefix = "MCP"
)

# Script-level variables for scope/role IDs
$script:McpReadScopeId = $null
$script:McpWriteScopeId = $null
$script:McpReadAllRoleId = $null
$script:McpReadWriteAllRoleId = $null

# =============================================================================
# Helper Functions
