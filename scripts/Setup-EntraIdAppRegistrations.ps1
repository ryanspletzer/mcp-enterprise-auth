function Write-Status {
    param(
        [string]$Message,
        [ValidateSet("Info", "Success", "Warning", "Error")]
        [string]$Type = "Info"
    )

    $colors = @{
        "Info"    = "Cyan"
        "Success" = "Green"
        "Warning" = "Yellow"
        "Error"   = "Red"
    }

    Write-Host $Message -ForegroundColor $colors[$Type]
}

function Get-OrCreateApplication {
    <#
    .SYNOPSIS
        Gets an existing app registration or creates a new one.
    #>
    [CmdletBinding()]
    param(
        [Parameter(Mandatory)]
        [string]$DisplayName,

        [Parameter()]
        [hashtable]$AppDefinition
    )

    # Search for existing app by displayName
    $existingApps = Get-MgApplication -Filter "displayName eq '$DisplayName'" -ErrorAction SilentlyContinue

    if ($existingApps -and $existingApps.Count -gt 0) {
        Write-Status "Found existing app: $DisplayName" -Type Warning
        return @{
            Application = $existingApps[0]
            Created     = $false
        }
    }

    # Create new application
    Write-Status "Creating app: $DisplayName" -Type Info
    $newApp = New-MgApplication @AppDefinition

    Write-Status "Created app: $DisplayName (AppId: $($newApp.AppId))" -Type Success
    return @{
        Application = $newApp
        Created     = $true
    }
}

function Ensure-ServicePrincipal {
    <#
    .SYNOPSIS
        Ensures a service principal exists for an application.
    #>
    [CmdletBinding()]
    param(
        [Parameter(Mandatory)]
        [string]$AppId
    )

    # Check if service principal exists
    $sp = Get-MgServicePrincipal -Filter "appId eq '$AppId'" -ErrorAction SilentlyContinue

    if (-not $sp) {
        Write-Status "Creating service principal for app: $AppId" -Type Info
        $sp = New-MgServicePrincipal -AppId $AppId
    }

    return $sp
}

function Add-ClientSecret {
    <#
    .SYNOPSIS
        Adds a client secret to an application.
    #>
    [CmdletBinding()]
    param(
        [Parameter(Mandatory)]
        [string]$AppObjectId,

        [Parameter()]
        [string]$Description = "Auto-generated by setup script",

        [Parameter()]
        [int]$ValidityDays = 365
    )

    $passwordCredential = @{
        displayName = $Description
        endDateTime = (Get-Date).AddDays($ValidityDays)
    }

    $secret = Add-MgApplicationPassword -ApplicationId $AppObjectId -PasswordCredential $passwordCredential

    return $secret.SecretText
}

